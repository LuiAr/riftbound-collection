import assert from "node:assert/strict";
import { builderCards, cardsById, eligibleReferences, references, validateDeck, ownedInventory, representativeCard, assessDeck, cheapestPrice, cardIdFor, isBannedCard, exportDeck, strategyProfile } from "../lib/deck-builder";
import { displayCards } from "../lib/collection";
import { priceKey } from "../lib/prices";
import { readBuilderDeck } from "../lib/saved-builder-deck";
import inventory from "../data/initial-inventory.json";

const refs = eligibleReferences("rogue assassin");
assert.equal(refs.length, 10);
assert.ok(strategyProfile(refs).find((card) => card.cardId === "astral heron")?.essential);
const ireliaProfile = strategyProfile(eligibleReferences("blade dancer"));
assert.ok(ireliaProfile.find((card) => card.cardId === "astral heron"));
assert.equal(ireliaProfile.find((card) => card.cardId === "astral heron")?.essential, false, "An Akali engine annotation must not force Heron into another champion's strategy.");
for (const ref of references) assert.deepEqual(validateDeck(ref.entries), [], ref.name);
const anchor = refs[0].entries;
assert.equal(anchor.filter((e) => ["main", "chosen"].includes(e.section)).reduce((s, e) => s + e.quantity, 0), 40);
const removeRune = anchor.map((e) => e.section === "runes" ? { ...e, quantity: e.quantity - 1 } : e);
assert.ok(validateDeck(removeRune).some((e) => e.includes("12 runes")));
assert.ok(validateDeck(anchor.filter((e) => e.section !== "chosen")).some((e) => e.includes("chosen champion")));
const main = anchor.find((e) => e.section === "main")!;
assert.ok(validateDeck([...anchor, { ...main, section: "sideboard", quantity: 3 }]).some((e) => e.includes("copy limit")));
const battlefield = anchor.find((e) => e.section === "battlefields")!;
assert.ok(validateDeck([...anchor, battlefield]).some((e) => e.includes("twice")));
assert.ok(validateDeck(anchor.map((e) => e.section === "legend" ? { ...e, quantity: 2 } : e)).some((e) => e.includes("one Legend")));
assert.ok(validateDeck([...anchor, { cardId: "does not exist", quantity: 1, section: "main" }]).some((e) => e.includes("unknown card")));
const offDomain = builderCards.find((c) => c.type === "Unit" && c.domains.includes("Mind"))!;
assert.ok(validateDeck([...anchor, { cardId: offDomain.id, quantity: 1, section: "sideboard" }]).some((e) => e.includes("incompatible")));
const wrongSignature = builderCards.find((c) => c.super === "Signature" && !c.tags.includes("Akali"))!;
assert.ok(validateDeck([...anchor, { cardId: wrongSignature.id, quantity: 1, section: "sideboard" }]).some((e) => e.includes("champion tag")));
assert.ok(validateDeck([...anchor, { cardId: "shuriken flip", quantity: 2, section: "sideboard" }]).some((e) => e.includes("Signature")));
const dianaReference = references.find((ref) => ref.legendId === "scorn of the moon")!;
assert.deepEqual(validateDeck([...dianaReference.entries.filter((entry) => entry.cardId !== "flash"), { cardId: "ezreal prodigy", quantity: 1, section: "main" }]), [], "Domain-compatible Champions can have different tags from the Legend.");
assert.ok(validateDeck(dianaReference.entries.map((entry) => entry.section === "chosen" ? { ...entry, cardId: "ezreal prodigy" } : entry)).some((error) => error.includes("chosen champion")));
assert.ok(isBannedCard("The Dreaming Tree"));
assert.ok(isBannedCard("Stacked Deck"));
const cards = displayCards(inventory.rows);
const owned = ownedInventory(cards);
assert.equal(owned["diana no longer human"], 1);
const diana = cards.find((c) => c.code === "ven-183-166")!;
assert.equal(cardIdFor(diana), "diana no longer human");
const regularDiana = representativeCard("diana no longer human", [])!;
assert.equal(ownedInventory([{ ...diana, quantity: 1 }, { ...regularDiana, quantity: 2 }])["diana no longer human"], 3);
assert.equal(ownedInventory(cards, { "diana no longer human": 2 })["diana no longer human"], 3);
assert.equal(ownedInventory(cards)["diana no longer human"], 1);
const fullOwned = Object.fromEntries(anchor.map((e) => [e.cardId, 20]));
const noPurchases = assessDeck(anchor, fullOwned, null, null, 0);
assert.equal(noPurchases.totalSek, 0);
assert.equal(noPurchases.unpricedCopies, 0);
assert.equal(noPurchases.ownedOnlyValid, true);
const empty = assessDeck(anchor, {}, null, null, 1000);
assert.equal(empty.budgetValid, false);
assert.ok(empty.unpricedCopies > 0);
const quote = { createdAt: "2026-10-03", quotes: {}, playableOffers: { "diana no longer human": [{ set: "Unleashed", productId: 1, standard: 10, foil: 5, printingVerified: false }] } };
const fx = { date: "2026-10-02", eurSek: 10, usdSek: 9 };
assert.equal(cheapestPrice("diana no longer human", quote, fx)?.unitSek, 50);
assert.equal(cheapestPrice("diana no longer human", quote, fx)?.finish, "Foil");
const purchase = assessDeck([{ cardId: "diana no longer human", quantity: 3, section: "main" }], { "diana no longer human": 1 }, quote, fx, 100);
assert.equal(purchase.lines[0].missing, 2);
assert.equal(purchase.totalSek, 100);
assert.equal(cardsById.get("astral heron")?.text.includes("this turn"), true);
for (const ref of references) {
  const proposal = { ...ref, summary: "", referenceIds: [ref.id], replacements: [], limitations: [] };
  const restored = readBuilderDeck(ref.name, exportDeck(proposal));
  assert.ok(restored, ref.name);
  assert.equal(restored.name, ref.name);
  assert.equal(exportDeck(restored), exportDeck(proposal), "Saving and reopening must preserve every quantity and section.");
  assert.deepEqual(validateDeck(restored.entries), []);
}
assert.equal(readBuilderDeck("Invalid", "legend\n1 Unknown Card"), null);
assert.equal(readBuilderDeck("Empty", ""), null);
assert.equal(readBuilderDeck("Malformed", "1 Akali, Deadly Weapon"), null);
const outdated = { name: "Needs review", entries: [...anchor, { cardId: "shuriken flip", quantity: 3, section: "sideboard" as const }], strategy: "", summary: "", referenceIds: [], replacements: [], limitations: [] };
assert.ok(readBuilderDeck(outdated.name, exportDeck(outdated)), "A saved deck with legality warnings must remain visible.");
console.log(`Deck builder checks passed: ${references.length} source lists, legality, printing identity, incomplete inventory, missing-copy costs and unpriced budgets.`);
